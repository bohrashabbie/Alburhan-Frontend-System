export function translate(locale: Locale, text: string) {
  return locale === "ar" ? (AR[text] ?? text) : text;
}

/** Arabic name when the locale is Arabic and one exists, else the English name. */
export function localName(locale: Locale, item: { name: string; name_ar?: string } | undefined) {
  if (!item) return "";
  return locale === "ar" && item.name_ar ? item.name_ar : item.name;
}
